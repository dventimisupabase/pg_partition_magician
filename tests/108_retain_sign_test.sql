-- ======================= (C) defence in depth: a config.retain written by hand =======================
-- The issue's shape: obtain 3, so the grid is [0, 1000) with ids 1..7, [1000, 2000) with 3 rows, [2000, 3000)
-- empty and [3000, 4000) holding the frontier row 3500. With the legitimate retain of 1500 the boundary is
-- floor(2000) = 2000 and exactly the first two are aged. The value is then edited by hand to -5000, which is
-- what neither transmute nor set_retain can prevent: that boundary is floor(8500) = 8000, above every
-- partition there is, and pre-fix the tick dropped all four and left the table empty and unwritable.
create table public.rs108h (id bigint generated by default as identity primary key, payload text);
insert into public.rs108h (payload) select 'x' from generate_series(1, 7);
call pgpm.transmute('public.rs108h', 'id', 1000, p_retain => 1500, p_paused => false, p_obtain => 3);
insert into public.rs108h (id, payload) select g, 'y' from generate_series(1001, 1003) g;
insert into public.rs108h (id, payload) values (3500, 'frontier');

create table pgpm_test108.h_before as
  select lo, child_name from pgpm.part where parent_table = 'public.rs108h'::regclass and attached;
select is((select array_agg(lo order by lo::numeric) from pgpm_test108.h_before), array['0', '1000', '2000', '3000'],
  'setup: four attached partitions, two of them below the legitimate horizon (the tick has real work to refuse)');

update pgpm.config set retain = '-5000' where parent_table = 'public.rs108h'::regclass;   -- THE HAND EDIT

select throws_like(
  $$ select pgpm._retain_boundary(c) from pgpm.config c where c.parent_table = 'public.rs108h'::regclass $$,
  '%is negative%', '_retain_boundary refuses to compute a horizon from a negative config.retain');

call pgpm.maintain('public.rs108h') \gset
select ok(:'p_status' like 'archived=0 dropped=0%write_block_deferred%retain_deferred%',
  'the tick deferred both the write-block and the retain step: ' || :'p_status');
select is(
  (select count(*)::int from pgpm.log
    where parent_table = 'public.rs108h'::regclass and action = 'skip_write_block' and method like '%is negative%'),
  1, 'skip_write_block was logged once, carrying the refusal');
select is(
  (select count(*)::int from pgpm.log
    where parent_table = 'public.rs108h'::regclass and action = 'skip_retain' and method like '%is negative%'),
  1, 'skip_retain was logged once, carrying the refusal');
select is(
  (select count(*)::int from pgpm.log where parent_table = 'public.rs108h'::regclass and action = 'retain_drop'),
  0, 'nothing was dropped');
select is(
  (select array_agg(child_name order by lo::numeric) from pgpm.part
    where parent_table = 'public.rs108h'::regclass and attached),
  (select array_agg(child_name order by lo::numeric) from pgpm_test108.h_before),
  'every partition that was attached before the tick is attached after it, by name');
select is((select array_agg(id order by id) from public.rs108h),
  array[1, 2, 3, 4, 5, 6, 7, 1001, 1002, 1003, 3500]::bigint[],
  'every row is still there, the aged ones included');
select lives_ok(
  $$ insert into public.rs108h (id, payload) values (3501, 'still live') $$,
  'the table is live: a write at the frontier is accepted');
select is((select count(*) from public.rs108h where id = 3501), 1::bigint,
  'and it landed');

-- status() is the diagnostic, so it must not be the thing that dies
select ok((select count(*) from pgpm.status()) = (select count(*) from pgpm.config),
  'status() still returns a row for every managed table');
select is((select retain from pgpm.status() where parent = 'public.rs108h'::regclass), '-5000',
  'status() shows the offending value');
select is((select retain_backlog from pgpm.status() where parent = 'public.rs108h'::regclass), null::bigint,
  'status().retain_backlog is null for it: there is no honest count of what such a horizon makes eligible');

-- the repair path is open: set_retain works from the bad state (a loose value, which drops nothing)
select lives_ok(
