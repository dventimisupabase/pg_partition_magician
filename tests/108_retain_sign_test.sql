-- ======================= (C) defence in depth: regrain_step has its own copy of the horizon =======================
-- regrain skips sub-ranges entirely below the horizon and discards their rows with the coarse source at the
-- swap, never copied. Against a future horizon that is every sub-range: the whole monolith, discarded.
create table public.rs108r (id bigint generated by default as identity primary key, payload text);
insert into public.rs108r (payload) select 'x' from generate_series(1, 50000);   -- ids 1..50000
call pgpm.transmute('public.rs108r', 'id', 10000, p_retain => 30000);   -- monolith [0, 60000)
select pgpm.obtain('public.rs108r');
insert into public.rs108r (id, payload) values (65000, 'frontier');    -- the monolith is frozen

select child_name as r_mono from pgpm.part where parent_table = 'public.rs108r'::regclass and lo = '0' \gset

update pgpm.config set retain = '-30000' where parent_table = 'public.rs108r'::regclass;   -- THE HAND EDIT

select is(pgpm.regrain_step('public.rs108r', :'r_mono'), 'prepared',
  'setup: the first regrain_step call installs change capture, which happens before the horizon is computed');
-- (built with format(): psql does not interpolate :'r_mono' inside a dollar-quoted string)
select throws_like(
  format($$ select pgpm.regrain_step('public.rs108r', %L) $$, :'r_mono'),
  '%is negative%', 'regrain_step refuses to compute a horizon from a negative config.retain');
select is(
  (select count(*)::int from pgpm.log
    where parent_table = 'public.rs108r'::regclass and action in ('regrain_aged', 'regrain_copy')),
  0, 'no sub-range was marked aged and none was copied');
select ok(
  (select attached from pgpm.part where parent_table = 'public.rs108r'::regclass and child_name = :'r_mono'),
  'the monolith is still attached');
select is(
  (select array_agg(id order by id) from public.rs108r where id in (1, 29999, 30000, 50000, 65000)),
  array[1, 29999, 30000, 50000, 65000]::bigint[],
  'the sentinel rows on both sides of the legitimate horizon are all still there');

-- POSITIVE CONTROL: the same regrain with the sign right (tests/07's shape): the 3 within-horizon
-- sub-ranges are copied, the 3 below it are skipped as aged and their rows discarded with the source.
update pgpm.config set retain = '30000' where parent_table = 'public.rs108r'::regclass;
select is(pgpm.regrain_history('public.rs108r'), 3,
  'with the sign right, regrain copies exactly the 3 within-horizon sub-ranges');
select is(
  (select array_agg(distinct lo order by lo) from pgpm.log
    where parent_table = 'public.rs108r'::regclass and action = 'regrain_aged'),
  array['0', '10000', '20000'], 'the 3 below-horizon sub-ranges were skipped as aged, by lo');
select is(
  (select array_agg(id order by id) from public.rs108r where id in (1, 29999, 30000, 50000, 65000)),
  array[30000, 50000, 65000]::bigint[],
  'the rows below the legitimate horizon are gone and the rest remain');

