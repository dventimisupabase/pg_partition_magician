-- p_retain cannot be negative (issue #451).
--
-- Neither transmute overload checked the sign of p_retain. A negative interval or count put the retention
-- horizon in the FUTURE: _retain_boundary subtracts retain from the frontier and nothing downstream
-- questioned a boundary above it, so on the next tick _enforce_write_blocks blocked every partition and
-- retain() dropped them all, the monolith and the partition taking writes included. The next insert failed
-- with `no partition of relation ... found for row`. A sign typo was all it took. set_retain caught a
-- negative value only through its would-drop guard, which compares boundaries, so a value whose boundary
-- grid-floored to the same place as the current one slipped straight through and armed a later tick.
--
-- ZERO IS NOT THE DEFECT. retain 0 puts the horizon at grid_floor(frontier), the write partition's own
-- floor; that partition has hi > boundary, so it is never eligible, and zero means "keep only the partition
-- taking writes, everything behind it is aged" (tests/63 relies on exactly that). Only a negative value puts
-- the horizon PAST the write partition, so only a negative value is refused. Zero is asserted ACCEPTED here
-- at both entry points and for both kinds, with a tick showing what it does.
--
-- Three layers, each pinned here:
--   (A) both transmute overloads refuse a negative p_retain BEFORE anything is committed (time and id);
--   (B) set_retain refuses a negative p_retain unconditionally (time and id), including the value the
--       would-drop guard alone cannot see;
--   (C) defence in depth for a config.retain edited by hand: _retain_boundary and regrain_step refuse to
--       compute a horizon from it, so a tick logs skip_write_block / skip_retain (exact actions) and drops
--       nothing, status() stays alive, and set_retain can still repair it.
-- Plus the positive controls that show none of this is a blanket refusal: zero and a retain SHORTER than one
-- partition_step are both accepted, and the tick drops exactly the aged partitions while keeping the one
-- holding the frontier. In those fixtures the horizon lands exactly ON the frontier partition's grid floor,
-- which is the case an "at or above the frontier's floor" check would have wrongly refused.
--
-- WHICH ASSERTIONS DISCRIMINATE (the tests/83 caveat): throws_like wraps the CALL in a function, and a
-- committing procedure cannot commit inside one, so against pre-fix code the transmute CALLs in (A) die at
-- phase 1's COMMIT with 2D000. The throws_like fails on the message, for the right reason, but the
-- untouched-table assertions right after it pass pre-fix too; read them as the post-fix contract (refused
-- before any COMMIT), not as the proof. Section (C) is where pre-fix code shows the actual data loss: every
-- partition dropped, every row gone, and regrain discarding every sub-range as aged.
create extension if not exists pgtap;
select plan(70);

create schema pgpm_test108;

-- ======================= (A) transmute refuses a negative p_retain, accepts zero: time =======================
create table public.rs108t (id bigint generated by default as identity, ts timestamptz not null, payload text,
  primary key (ts, id));
insert into public.rs108t (ts, payload)
  select now() - (g || ' minutes')::interval, 'x' from generate_series(1, 100) g;

select throws_like(
  $$ call pgpm.transmute('public.rs108t', 'ts', interval '1 day', p_retain => interval '-1 day', p_paused => false, p_obtain => 3) $$,
  '%cannot be negative%', 'transmute (time) refuses a negative p_retain with the pgpm message');

-- refused up front: nothing committed, nothing left on the table for the operator to clean up
select is((select relkind::text from pg_class where oid = 'public.rs108t'::regclass), 'r',
  'the time table is untouched');
select is((select count(*) from pgpm.config where parent_table = 'public.rs108t'::regclass), 0::bigint,
  'the time table was not registered');
select is((select count(*) from pgpm.transmute_inflight), 0::bigint,
  'no claim was recorded');
select ok(not exists (select 1 from pg_constraint
                       where conrelid = 'public.rs108t'::regclass and conname = 'pgpm_monolith_bound'),
  'no bound CHECK was left behind');

-- LIVENESS WITNESS and positive control: the identical call with retain ZERO succeeds. Without this the
-- refusal above would pass against a build where transmute is broken for any reason at all.
call pgpm.transmute('public.rs108t', 'ts', interval '1 day', p_retain => interval '0', p_paused => false, p_obtain => 3);

select is((select relkind::text from pg_class where oid = 'public.rs108t'::regclass), 'p',
  'the same call succeeds with retain = 0');
select is((select retain from pgpm.config where parent_table = 'public.rs108t'::regclass), '00:00:00',
  'config.retain holds the zero retain');
-- zero puts the horizon exactly on the write partition's own floor, grid_floor(now()); that partition has
-- hi > boundary and is never eligible
select is(
  (select pgpm._retain_boundary(c) from pgpm.config c where c.parent_table = 'public.rs108t'::regclass),
  pgpm._grid_floor('time', '1 day', '2000-01-01 00:00:00+00', now()::text, 'UTC'),
  'retain 0 puts the horizon exactly on the frontier partition''s grid floor');

select child_name as t_write from pgpm.part
  where parent_table = 'public.rs108t'::regclass and attached
    and not pgpm._native_gt('time', lo, now()::text) and pgpm._native_gt('time', hi, now()::text) \gset

call pgpm.maintain('public.rs108t') \gset
select ok(:'p_status' like 'archived=0 dropped=0%' and :'p_status' not like '%deferred%',
  'a tick against retain 0 defers nothing and, with nothing behind the write partition on a fresh time grid, drops nothing: ' || :'p_status');
select is(
  (select count(*)::int from pgpm.log
    where parent_table = 'public.rs108t'::regclass and action in ('skip_write_block', 'skip_retain')),
  0, 'no skip_write_block / skip_retain was logged for retain 0');
select ok(
  (select attached from pgpm.part where parent_table = 'public.rs108t'::regclass and child_name = :'t_write'),
  'the partition holding now() survives the tick');
select lives_ok(
  $$ insert into public.rs108t (ts, payload) values (now(), 'live') $$,
  'the time table is live: a write at now() is accepted');
select is((select count(*) from public.rs108t), 101::bigint,
  'and it landed');

-- ======================= (A) transmute refuses a negative p_retain, accepts zero: id =======================
create table public.rs108i (id bigint generated by default as identity primary key, payload text);
insert into public.rs108i (payload) select 'x' from generate_series(1, 7);   -- ids 1..7

select throws_like(
  $$ call pgpm.transmute('public.rs108i', 'id', 1000, p_retain => -1000, p_paused => false) $$,
  '%cannot be negative%', 'transmute (id) refuses a negative p_retain with the pgpm message');
select is((select relkind::text from pg_class where oid = 'public.rs108i'::regclass), 'r',
  'the id table is untouched');
select is((select count(*) from pgpm.config where parent_table = 'public.rs108i'::regclass), 0::bigint,
  'the id table was not registered');

-- LIVENESS WITNESS and positive control: retain ZERO. Monolith [0, 1000) holds ids 1..7; [1000, 2000) gets
-- three rows; the frontier row 2500 lands in [2000, 3000). Zero means: keep [2000, 3000), everything behind
-- it is aged.
call pgpm.transmute('public.rs108i', 'id', 1000, p_retain => 0, p_paused => false);
insert into public.rs108i (id, payload) select g, 'y' from generate_series(1001, 1003) g;
insert into public.rs108i (id, payload) values (2500, 'frontier');

select child_name as i_mono from pgpm.part where parent_table = 'public.rs108i'::regclass and lo = '0' \gset
select child_name as i_sib  from pgpm.part where parent_table = 'public.rs108i'::regclass and lo = '1000' \gset
select child_name as i_live from pgpm.part where parent_table = 'public.rs108i'::regclass and lo = '2000' \gset

select is((select retain from pgpm.config where parent_table = 'public.rs108i'::regclass), '0',
  'the same call succeeds with retain = 0');
-- boundary = floor(2500 - 0) = 2000 = floor(frontier): the horizon is the write partition's own floor.
-- Everything with hi <= 2000 is aged; [2000, 3000) itself is not.
select is(
  (select pgpm._retain_boundary(c) from pgpm.config c where c.parent_table = 'public.rs108i'::regclass),
  pgpm._grid_floor('id', '1000', '0', pgpm._frontier_native('public.rs108i'), 'UTC'),
  'retain 0 lands the horizon exactly on the frontier partition''s grid floor');
select is(
  (select pgpm._retain_boundary(c) from pgpm.config c where c.parent_table = 'public.rs108i'::regclass),
  '2000', 'and that floor is 2000');

call pgpm.maintain('public.rs108i') \gset
select ok(:'p_status' like 'archived=0 dropped=2%' and :'p_status' not like '%deferred%',
  'the tick drops the two partitions behind the write partition and defers nothing: ' || :'p_status');
select is(
  (select array_agg(lo order by lo::numeric) from pgpm.log
    where parent_table = 'public.rs108i'::regclass and action = 'retain_drop'),
  array['0', '1000'], 'retain_drop was logged for exactly [0, 1000) and [1000, 2000)');
select ok(to_regclass(format('public.%I', :'i_mono')) is null and to_regclass(format('public.%I', :'i_sib')) is null,
  'the two aged partitions are gone');
select ok(
  (select attached from pgpm.part where parent_table = 'public.rs108i'::regclass and child_name = :'i_live'),
  'the partition holding the frontier survives: zero keeps exactly it');
select is((select array_agg(id order by id) from public.rs108i), array[2500]::bigint[],
  'exactly the frontier row survives; the aged rows went with their partitions (the legitimate policy)');
select lives_ok(
  $$ insert into public.rs108i (id, payload) values (2501, 'still live') $$,
  'the id table is live: a write at the frontier is accepted');
select is((select array_agg(id order by id) from public.rs108i), array[2500, 2501]::bigint[],
  'and it landed');

-- ======================= (B) set_retain refuses a negative p_retain, accepts zero =======================
-- time (config.retain is 0)
select throws_like(
  $$ select pgpm.set_retain('public.rs108t', '-1 day') $$,
  '%cannot be negative%', 'set_retain (time) refuses a negative p_retain');
select is((select retain from pgpm.config where parent_table = 'public.rs108t'::regclass), '00:00:00',
  'the refused call left the time table''s config.retain untouched');
-- a positive retain SHORTER than one partition_step is accepted (loosening from zero)
select lives_ok(
  $$ select pgpm.set_retain('public.rs108t', '1 hour') $$,
  'set_retain (time) accepts a positive retain shorter than the 1 day step');
select is((select retain from pgpm.config where parent_table = 'public.rs108t'::regclass), '1 hour',
  'config.retain was updated to 1 hour (set_retain stores the text as given; transmute stores the cast interval)');
-- its horizon sits at or below the grid floor of now(): "at" is legitimate (retain 1 hour at 15:00 floors to
-- today 00:00, as does now()), and it is never past the write partition
select ok(
  not pgpm._native_gt('time',
    (select pgpm._retain_boundary(c) from pgpm.config c where c.parent_table = 'public.rs108t'::regclass),
    pgpm._grid_floor('time', '1 day', '2000-01-01 00:00:00+00', now()::text, 'UTC')),
  'a sub-step retain puts the horizon at or below the frontier partition''s floor, never past it');
-- and back to zero: the horizon returns to the write partition's floor, which newly drops nothing
select lives_ok(
  $$ select pgpm.set_retain('public.rs108t', '0') $$,
  'set_retain (time) accepts zero');
select is((select retain from pgpm.config where parent_table = 'public.rs108t'::regclass), '0',
  'config.retain was updated to 0');

-- id (config.retain is 0, frontier 2501): THE WOULD-DROP GUARD'S BLIND SPOT. The current boundary is
-- floor(2501) = 2000. A retain of -400 gives floor(2901) = 2000: the same boundary, so nothing is newly
-- eligible and the guard alone would have ACCEPTED it. Then the frontier crosses 3000 and the -400 horizon
-- jumps to floor(3400) = 3000, dropping the partition the frontier is in. The sign check is what refuses it.
select throws_like(
  $$ select pgpm.set_retain('public.rs108i', '-400') $$,
  '%cannot be negative%', 'set_retain (id) refuses a negative p_retain whose boundary equals the current one');
select is((select retain from pgpm.config where parent_table = 'public.rs108i'::regclass), '0',
  'the refused call left the id table''s config.retain untouched');
select lives_ok(
  $$ select pgpm.set_retain('public.rs108i', '500') $$,
  'set_retain (id) accepts a positive retain shorter than the 1000 step');
select is((select retain from pgpm.config where parent_table = 'public.rs108i'::regclass), '500',
  'config.retain was updated to 500');
select is(
  (select pgpm._retain_boundary(c) from pgpm.config c where c.parent_table = 'public.rs108i'::regclass),
  '2000', 'retain 500 at a frontier of 2501 lands on the same floor zero did: 2000');
select lives_ok(
  $$ select pgpm.set_retain('public.rs108i', '0') $$,
  'set_retain (id) accepts zero (same boundary, nothing newly eligible)');
select is((select retain from pgpm.config where parent_table = 'public.rs108i'::regclass), '0',
  'config.retain was updated to 0');

-- what zero does after set_retain, too: the write partition survives a tick
call pgpm.maintain('public.rs108i') \gset
select ok(:'p_status' like 'archived=0 dropped=0%' and :'p_status' not like '%deferred%',
